import assert from 'node:assert/strict';
import {VariantMatch} from '../dist/variants.js';
import {nextBallTargets} from '../dist/ball-targets.js';
const balls=['Blue','Red','Black','Yellow'].map(name=>({name,x:0,z:0,entered:true}));
const match=new VariantMatch('association',balls,2);
balls[0].progress=0;balls[1].progress=7;balls[2].progress=12;balls[3].finished=true;
let targets=nextBallTargets(match,balls);
assert.equal(targets[0].label,'Hoop 1 · ↑ North');
assert.equal(targets[1].label,'Hoop 1 · ↓ South');
assert.equal(targets[2].label,'Centre peg');
assert.equal(targets[3].label,'Finished');
assert.equal(targets[0].name,'Blue');assert.equal(targets[1].index,1);
const individual=new VariantMatch('association',balls,3);
assert.equal(nextBallTargets(individual,balls).length,3);
const nine=new VariantMatch('nine',balls,2);balls[0].progress=7;
assert.equal(nextBallTargets(nine,balls)[0].label,'Turning stake');
balls[0].progress=15;assert.equal(nextBallTargets(nine,balls)[0].label,'Finish stake');
assert.deepEqual(nextBallTargets(null,balls),[]);
console.log('PASS: per-ball targets, returning hoop direction, peg, finished balls, multiplayer roster, Backyard stakes and Golf omission');
